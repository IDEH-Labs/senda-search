def get_curated_seed_urls(category: Optional[str] = None) -> List[str]:
    """Retrieve filtered list of URLs from the curated seed list."""
    if not category:
        return [s.url for s in CURATED_SEEDS]
    clean_cat = category.strip().lower()
    return [s.url for s in CURATED_SEEDS if s.category == clean_cat]


def get_seeds_by_country(country_code: str) -> List[SeedDefinition]:
    """Retrieve curated seeds associated with a specific ISO country code."""
    code = country_code.strip().upper()
    return [s for s in CURATED_SEEDS if (s.country_code or "").upper() == code]


def get_government_seeds() -> List[SeedDefinition]:
    """Retrieve all public, governmental and multilateral seeds."""
    return [
        s for s in CURATED_SEEDS
        if s.category in ("gobierno_nacional", "gobierno_multilateral", "datos_publicos")
    ]
