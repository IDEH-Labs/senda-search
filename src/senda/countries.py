SOVEREIGN_BY_QID: Dict[str, SovereignCountry] = {
    c.wikidata_qid: c for c in SOVEREIGN_REGISTRY.values() if c.wikidata_qid
}

SOVEREIGN_BY_CODE: Dict[str, SovereignCountry] = {
    c.code.lower(): c for c in SOVEREIGN_REGISTRY.values()
}


def normalize_country_text(text: str) -> str:
    """Normalize country name or query token (lowercase, unaccent, strip symbols)."""
    if not text:
        return ""
    text = text.lower().strip()
    text = "".join(
        c for c in unicodedata.normalize("NFD", text)
        if unicodedata.category(c) != "Mn"
    )
    text = re.sub(r"[^\w\s]", " ", text)
    return " ".join(text.split())


# Index by normalized search terms & aliases
_SOVEREIGN_BY_TERM: Dict[str, SovereignCountry] = {}
for _c in SOVEREIGN_REGISTRY.values():
    _SOVEREIGN_BY_TERM[_c.code.lower()] = _c
    _SOVEREIGN_BY_TERM[normalize_country_text(_c.name_es)] = _c
    _SOVEREIGN_BY_TERM[normalize_country_text(_c.name_en)] = _c
    for _alias in _c.aliases:
        _SOVEREIGN_BY_TERM[normalize_country_text(_alias)] = _c

_NOISE_PREFIXES = (
    "gobierno de ",
    "gobierno del ",
    "gobierno de la ",
    "presidencia de ",
    "presidencia del ",
    "presidencia de la ",
    "portal de ",
    "portal del ",
    "portal oficial de ",
    "portal oficial del ",
    "republica de ",
    "republica del ",
    "republica democratica de ",
    "republica democratica del ",
    "republic of ",
    "estado de ",
    "estado del ",
    "datos de ",
    "datos del ",
    "datos abiertos de ",
    "pais ",
    "pais de ",
)


def get_sovereign_country(
    query: Optional[str] = None,
    qid: Optional[str] = None,
    code: Optional[str] = None,
) -> Optional[SovereignCountry]:
    """Resolve a sovereign nation by Wikidata Q-ID, ISO code, or search text."""
    if qid:
        clean_qid = qid.strip().upper()
        if clean_qid in SOVEREIGN_BY_QID:
            return SOVEREIGN_BY_QID[clean_qid]

    if code:
        clean_code = code.strip().lower()
        if clean_code in SOVEREIGN_BY_CODE:
            return SOVEREIGN_BY_CODE[clean_code]

    if query:
        norm_q = normalize_country_text(query)
        if not norm_q:
            return None

        # Direct term match
        if norm_q in _SOVEREIGN_BY_TERM:
            return _SOVEREIGN_BY_TERM[norm_q]

        # Strip standard institutional prefixes (e.g. "gobierno de colombia" -> "colombia")
        for pfx in _NOISE_PREFIXES:
            if norm_q.startswith(pfx):
                sub = norm_q[len(pfx):].strip()
                if sub in _SOVEREIGN_BY_TERM:
                    return _SOVEREIGN_BY_TERM[sub]

    return None


def get_country_name(code: Optional[str]) -> str:
    """Return Spanish country display name for an ISO country code."""
    if not code or code.lower() in ("all", "global", "none"):
        return "Global"
    code_lower = code.lower().strip()
    if code_lower in COUNTRY_BY_CODE:
        return f"{COUNTRY_BY_CODE[code_lower]} ({code.upper()})"
    return f"Región: {code.upper()}"


def get_countries_grouped() -> Dict[str, List[Dict[str, str]]]:
    """Return countries grouped by geographic continent/region."""
    grouped: Dict[str, List[Dict[str, str]]] = {}
    for item in COUNTRY_CATALOG:
        cont = item["continent"]
        if cont not in grouped:
            grouped[cont] = []
        grouped[cont].append(item)
    return grouped
